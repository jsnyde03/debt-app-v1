/**
 * 4.1.9b.5 + .6 — THE SMALL BUNDLE: per-flow results, and the files you actually read when a flow reds.
 *
 * ⚡ WHY IT EXISTS, MEASURED: diagnosing flow 10 needed a **48 MB / 122 MB** artifact pull to read ONE
 * string, and the deciding file — Maestro's view hierarchy at the failure — is **72 KB**. The big
 * `maestro-report-*` artifact still ships everything (screenshots are the whole point of a native lane);
 * this is the one you download first, and on a slow connection it is the difference between diagnosing a
 * red in a minute and putting it off.
 *
 * It carries two things:
 *   ① `native-lane-results-<tier>.json` — 4.1.9c's writer's input. 90-day retention on the artifact,
 *      because an input that expires in a week is an input that has to be regenerated by re-running a
 *      20-minute lane.
 *   ② every SMALL, TEXTUAL diagnostic Maestro wrote — the hierarchy dumps, `maestro.log`, the per-command
 *      JSON — and nothing else.
 *
 * ⛔ NO SILENT CAPS. Anything skipped for size, and the total, are printed and written into
 * `MANIFEST.txt`. A bundle that quietly dropped the one file you needed is worse than a big one: it
 * reads as "there was nothing to find".
 *
 * ⛔ ZERO DEPENDENCIES — the tier jobs run no `npm install` after 4.1.9b's split.
 *
 * Usage: node scripts/collect-lane-diagnostics.mjs --tier <iphone|ipad>
 */
import { readdirSync, statSync, mkdirSync, copyFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, relative, extname, basename, dirname } from 'node:path';
import { buildResults, writeResults, renderSummary, appendSummary } from './maestro-results.mjs';

const arg = (name, fallback = undefined) => {
  const i = process.argv.indexOf(`--${name}`);
  return i === -1 || i === process.argv.length - 1 ? fallback : process.argv[i + 1];
};

const tier = arg('tier', 'iphone');
const RN = arg('rn-dir', 'apps/rn');
const OUT = join(RN, 'lane-diagnostics');
const FLOW_DIR = join(RN, '.maestro');

// Per-tier inputs. The iPad tier writes its own report and TWO debug directories (light and the
// 4.1.5.6 dark re-run); the iPhone tier writes one of each.
const TIERS = {
  iphone: { junit: join(RN, 'maestro-report.xml'), debug: [join(RN, 'maestro-debug')] },
  ipad: {
    junit: join(RN, 'maestro-report-ipad.xml'),
    debug: [join(RN, 'maestro-debug-ipad'), join(RN, 'maestro-debug-ipad-dark'), join(RN, 'maestro-debug')],
  },
};
const cfg = TIERS[tier];
if (!cfg) {
  console.error(`unknown tier "${tier}" — expected one of ${Object.keys(TIERS).join(', ')}`);
  process.exit(2);
}

mkdirSync(OUT, { recursive: true });

// ── ① the results file ────────────────────────────────────────────────────────────────────────────
const results = buildResults({ junitPath: cfg.junit, tier, flowDir: FLOW_DIR });
const resultsPath = join(OUT, `native-lane-results-${tier}.json`);
writeResults(results, resultsPath);
const md = renderSummary(results);
appendSummary(md);
console.log(md);

// ── ② the small textual diagnostics ───────────────────────────────────────────────────────────────
// ⚠️ 2 MB per file. Maestro's hierarchy dumps are tens to hundreds of KB; `device-simulator.log` — the
// ENTIRE simulator syslog, 118 MB for flow 01 alone — is the thing this ceiling exists to exclude, and
// it is also excluded by name so the reason survives a future ceiling change.
const MAX_FILE = 2 * 1024 * 1024;
const MAX_TOTAL = 20 * 1024 * 1024;
const BINARY = new Set(['.png', '.jpg', '.jpeg', '.mp4', '.mov', '.zip', '.gz', '.tar', '.ips']);
const BY_NAME = new Set(['device-simulator.log']);

function walk(dir, acc = []) {
  let entries;
  try {
    entries = readdirSync(dir, { withFileTypes: true });
  } catch {
    return acc;
  }
  for (const e of entries) {
    const p = join(dir, e.name);
    if (e.isDirectory()) walk(p, acc);
    else if (e.isFile()) acc.push(p);
  }
  return acc;
}

const skipped = [];
let total = 0;
let copied = 0;

for (const debugDir of cfg.debug) {
  if (!existsSync(debugDir)) continue;
  for (const file of walk(debugDir)) {
    const name = basename(file);
    const size = statSync(file).size;
    if (BY_NAME.has(name)) { skipped.push([file, size, 'excluded by name (the full simulator syslog)']); continue; }
    if (BINARY.has(extname(file).toLowerCase())) { skipped.push([file, size, 'binary — it rides in the big artifact']); continue; }
    if (size > MAX_FILE) { skipped.push([file, size, `over the ${MAX_FILE / 1024 / 1024} MB per-file ceiling`]); continue; }
    if (total + size > MAX_TOTAL) { skipped.push([file, size, `over the ${MAX_TOTAL / 1024 / 1024} MB bundle ceiling`]); continue; }
    const dest = join(OUT, 'debug', relative(RN, file));
    mkdirSync(dirname(dest), { recursive: true });
    copyFileSync(file, dest);
    total += size;
    copied += 1;
  }
}

const kb = (n) => `${(n / 1024).toFixed(1)} KB`;
const manifest = [
  `tier: ${tier}`,
  `run: ${results.runId ?? '(local)'} attempt ${results.runAttempt ?? '—'}`,
  `sha: ${results.sha ?? '(local)'}`,
  `flows: ${results.totals.pass} passed · ${results.totals.fail} failed · ${results.totals.skipped} skipped`,
  `junit found: ${results.junitFound}`,
  '',
  `copied ${copied} file(s), ${kb(total)}`,
  '',
  ...(skipped.length
    ? ['skipped — stated rather than silent:', ...skipped.map(([f, s, why]) => `  ${f} (${kb(s)}) — ${why}`)]
    : ['skipped: nothing']),
  '',
].join('\n');
writeFileSync(join(OUT, 'MANIFEST.txt'), manifest, 'utf8');

console.log(`── lane diagnostics (${tier}) ──`);
console.log(manifest);
console.log(`→ ${resultsPath}`);
if (results.unresolved.length) console.error(`⚠️ unresolved testcase names: ${results.unresolved.join(', ')}`);
